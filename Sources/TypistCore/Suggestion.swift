import Foundation

/// A pending inline suggestion: the text that would be inserted at the caret.
public struct Suggestion: Equatable {
    public struct AcceptOptions: Equatable {
        /// Accepting a word also takes the space after it.
        public var includeTrailingSpace = false
        /// Punctuation glued to a word ("there,") is accepted with it.
        public var includeAttachedPunctuation = true

        public init(includeTrailingSpace: Bool = false, includeAttachedPunctuation: Bool = true) {
            self.includeTrailingSpace = includeTrailingSpace
            self.includeAttachedPunctuation = includeAttachedPunctuation
        }
    }

    public private(set) var remaining: String

    public init(_ text: String) {
        remaining = text
    }

    public var isEmpty: Bool { remaining.isEmpty }

    /// Turns raw model output into something worth showing, or `nil`.
    ///
    /// - Parameters:
    ///   - raw: Text generated by the model.
    ///   - before: Text before the caret, used to avoid doubled whitespace.
    ///   - maxWords: Upper bound on suggested words.
    ///   - truncated: Generation hit its token limit, so the last word may be
    ///     cut off mid-way and is dropped (unless it is the only one).
    public static func make(raw: String, before: String, maxWords: Int, truncated: Bool = false) -> Suggestion? {
        var text = Substring(raw)
        if let newline = text.firstIndex(where: \.isNewline) {
            text = text[..<newline]
        }
        if before.last?.isWhitespace ?? true {
            text = text.drop(while: \.isWhitespace)
        }

        var chunks = Self.chunks(of: text)
        if truncated, chunks.count > 1, !(text.last?.isWhitespace ?? false) {
            chunks.removeLast()
        }
        let limited = chunks.prefix(max(maxWords, 0)).joined()
        let result = limited.replacingOccurrences(of: "\\s+$", with: "", options: .regularExpression)
        return result.isEmpty ? nil : Suggestion(result)
    }

    /// The next word, including the whitespace leading up to it.
    public func nextChunk(_ options: AcceptOptions = AcceptOptions()) -> String {
        guard var chunk = Self.chunks(of: Substring(remaining)).first else { return "" }
        if !options.includeAttachedPunctuation {
            let word = chunk.drop(while: \.isWhitespace)
            if let firstWordCharacter = word.firstIndex(where: { $0.isLetter || $0.isNumber }) {
                // Stop before trailing punctuation: " there," -> " there".
                let afterWord = word[firstWordCharacter...].firstIndex { !($0.isLetter || $0.isNumber || $0 == "'" || $0 == "’" || $0 == "-") }
                if let afterWord { chunk = chunk[..<afterWord] }
            } else if let first = word.indices.first {
                // Only punctuation left: take one mark at a time.
                chunk = chunk[...first]
            }
        }
        var result = String(chunk)
        if options.includeTrailingSpace, remaining.dropFirst(result.count).first == " " {
            result += " "
        }
        return result
    }

    /// Removes and returns the next word.
    public mutating func acceptNextChunk(_ options: AcceptOptions = AcceptOptions()) -> String {
        let chunk = nextChunk(options)
        remaining.removeFirst(chunk.count)
        return chunk
    }

    /// Removes and returns everything.
    public mutating func acceptAll() -> String {
        defer { remaining = "" }
        return remaining
    }

    /// Call when the user typed `typed` themselves. If it matches the start of
    /// the suggestion the suggestion shrinks and stays valid ("typing through");
    /// otherwise it is invalid and `false` is returned.
    public mutating func consume(typed: String) -> Bool {
        guard !typed.isEmpty, remaining.hasPrefix(typed) else { return false }
        remaining.removeFirst(typed.count)
        return true
    }

    /// Splits into `whitespace* non-whitespace+` pieces; trailing whitespace is dropped.
    static func chunks(of text: Substring) -> [Substring] {
        var result: [Substring] = []
        var index = text.startIndex
        while index < text.endIndex {
            let start = index
            while index < text.endIndex, text[index].isWhitespace { index = text.index(after: index) }
            guard index < text.endIndex else { break }
            while index < text.endIndex, !text[index].isWhitespace { index = text.index(after: index) }
            result.append(text[start..<index])
        }
        return result
    }
}

public extension String {
    var wordCount: Int { split(whereSeparator: \.isWhitespace).count }
}
